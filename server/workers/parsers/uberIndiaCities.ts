/** slug -> {slug, city}: strips the trailing '-in' and the Indian state suffix. */
const PARSED: UberIndiaCity[] = SLUGS.map((slug: string) => {
  let rest = slug.endsWith('-in') ? slug.slice(0, -3).split('-') : slug.split('-');
  const tail2 = rest.length > 2 ? `${rest[rest.length - 2]}-${rest[rest.length - 1]}` : '';
  const tail1 = rest[rest.length - 1];
  if (UBER_IN_STATE_SUFFIXES.has(tail2)) rest = rest.slice(0, -2);
  else if (UBER_IN_STATE_SUFFIXES.has(tail1)) rest = rest.slice(0, -1);
  return { slug, city: rest.map((w: string) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ') };
});


const BY_CANON = new Map<string, UberIndiaCity>();
for (const e of PARSED) {
  const k = canonCity(e.city);
  if (!BY_CANON.has(k)) BY_CANON.set(k, e);
}

/** Resolve a city/place string to Uber's own published India city page (canonical-name match).
 *  Whole-word matching only: naive includes() made "bengaluru" match the town "alur". */
export function uberIndiaCityFor(place: string): UberIndiaCity | null {
  if (!place) return null;
  const t = canonCity(place);
  const hit = BY_CANON.get(t);
  if (hit) return hit;
  // district-style names ("Juni Indore Tahsil") match their city as a whole word
  const esc = (x: string) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  let best: UberIndiaCity | null = null;
  let bestLen = 0;
  for (const [k, v] of BY_CANON) {
    if ((new RegExp(`\\b${esc(k)}\\b`)).test(t) || (new RegExp(`\\b${esc(t)}\\b`)).test(k)) {
      if (k.length > bestLen) { best = v; bestLen = k.length; }
    }
  }
  return best;
}

